#!/usr/bin/env python3
"""
Compare fixed-window and semantic chunking on a set of queries.

For each language in benchmarks/queries.json two ChromaDB collections are
expected: <lang>_fixed and <lang>_semantic (create them with ingest.py using
--collection and --chunking). For every query the script records, per regime:

* the top retrieved chunks and their distances
* retrieval metrics: whether the top-1 / top-5 chunks contain all of the
  query's key terms, the term coverage of the top-1 chunk, and whether the
  top-1 chunk starts and ends on a clean boundary
* optionally, an answer generated by an Ollama model from the retrieved
  context, and a 1-5 correctness score from a second (judge) model that
  compares the answer against a reference answer without knowing which
  regime produced it.

Usage:
    python benchmarks/compare_chunking.py --port 8765 \
        --ollama-url http://localhost:11434 \
        --answer-model qwen3.5:4b --judge-model qwen3-next:80b-a3b-instruct
    python benchmarks/compare_chunking.py --port 8765 --skip-llm   # retrieval only
"""

import argparse
import json
import re
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import chromadb
import requests

REGIMES = ["fixed", "semantic"]
TOP_K = 5

RAG_PROMPT = """You are a helpful assistant with access to {language} programming language documentation.
Use the following context to answer the user's question. If the context doesn't contain relevant information,
say so and provide a general helpful response about {language} programming.

Context:
{context}

User Question: {question}

Please provide a clear, helpful answer based on the context provided."""

JUDGE_PROMPT = """You are grading the answer a documentation chatbot gave to a user's question.

Question:
{question}

Reference answer (written by an expert from the same documentation):
{reference}

Chatbot answer:
{answer}

Score the chatbot answer for factual correctness and completeness against the
reference on a 1 to 5 scale:
5 = correct and covers every important point in the reference
4 = correct, misses a minor point
3 = mostly correct but misses a major point or is vague
2 = partly wrong or mostly missing
1 = wrong, off-topic, or says the information is unavailable

Reply with JSON only, like {{"score": 4, "reason": "one sentence"}}."""


def squash(text: str) -> str:
    """Lower-case and drop all whitespace so PDF spacing glitches don't matter."""
    return re.sub(r"\s+", "", text.lower())


def contains_all(text: str, terms) -> bool:
    body = squash(text)
    return all(squash(t) in body for t in terms)


def coverage(text: str, terms) -> float:
    body = squash(text)
    return sum(squash(t) in body for t in terms) / len(terms)


def clean_start(chunk: str) -> bool:
    """Does the chunk begin at a sentence or heading rather than mid-sentence?"""
    first = chunk.lstrip()[:1]
    return first.isupper() or first.isdigit() or first in "(\"'>“‘"


def clean_end(chunk: str) -> bool:
    return chunk.rstrip()[-1:] in ".!?:)\"'”’"


def ollama_generate(url, model, prompt, timeout=600):
    payload = {"model": model, "prompt": prompt, "stream": False, "think": False,
               "options": {"temperature": 0}}
    r = requests.post(f"{url}/api/generate", json=payload, timeout=timeout)
    r.raise_for_status()
    text = r.json().get("response", "")
    # Strip any thinking block a reasoning model may still emit.
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.S).strip()
    return text


def judge(url, model, question, reference, answer):
    raw = ollama_generate(url, model, JUDGE_PROMPT.format(
        question=question, reference=reference, answer=answer))
    match = re.search(r"\{.*\}", raw, flags=re.S)
    try:
        data = json.loads(match.group(0)) if match else {}
        score = int(data.get("score"))
        return max(1, min(5, score)), str(data.get("reason", ""))
    except (ValueError, TypeError, AttributeError, json.JSONDecodeError):
        pass
    # The model sometimes puts unescaped quotes or newlines inside "reason";
    # fall back to pulling the score and reason out with regexes.
    score_match = re.search(r'"score"\s*:\s*([1-5])', raw)
    reason_match = re.search(r'"reason"\s*:\s*"(.*?)"?\s*\}?\s*$', raw, flags=re.S)
    if score_match:
        reason = reason_match.group(1).strip() if reason_match else raw.strip()
        return int(score_match.group(1)), reason[:500]
    return None, f"unparseable judge output: {raw[:200]}"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--host", default="localhost")
    parser.add_argument("--port", type=int, default=8002)
    parser.add_argument("--queries", default=str(Path(__file__).with_name("queries.json")))
    parser.add_argument("--output", default=str(Path(__file__).with_name("results.json")))
    parser.add_argument("--languages", nargs="*", help="Subset of language keys to run")
    parser.add_argument("--ollama-url", default="http://127.0.0.1:11434")
    parser.add_argument("--answer-model", default="qwen3.5:4b")
    parser.add_argument("--judge-model", default="qwen3-next:80b-a3b-instruct")
    parser.add_argument("--skip-llm", action="store_true", help="Retrieval metrics only")
    args = parser.parse_args()

    spec = json.load(open(args.queries))
    client = chromadb.HttpClient(host=args.host, port=args.port)

    results = {
        "run_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "top_k": TOP_K,
        "answer_model": None if args.skip_llm else args.answer_model,
        "judge_model": None if args.skip_llm else args.judge_model,
        "languages": {},
    }

    for key, lang in spec.items():
        if args.languages and key not in args.languages:
            continue
        collections = {}
        for regime in REGIMES:
            collections[regime] = client.get_collection(f"{key}_{regime}")
        out = {
            "name": lang["name"],
            "source": lang["source"],
            "chunk_counts": {r: collections[r].count() for r in REGIMES},
            "queries": [],
        }
        print(f"\n### {lang['name']}  chunks: {out['chunk_counts']}")

        for q in lang["queries"]:
            entry = {"level": q["level"], "question": q["question"],
                     "key_terms": q["key_terms"], "regimes": {}}
            print(f"\n[{q['level']}] {q['question']}")
            for regime in REGIMES:
                t0 = time.time()
                res = collections[regime].query(
                    query_texts=[q["question"]], n_results=TOP_K,
                    include=["documents", "metadatas", "distances"])
                search_s = time.time() - t0
                docs = res["documents"][0]
                dists = res["distances"][0]
                metas = res["metadatas"][0]
                top1 = docs[0] if docs else ""
                reg = {
                    "search_seconds": round(search_s, 3),
                    "chunks": [
                        {"text": d, "distance": round(float(dist), 4),
                         "chunk_index": m.get("chunk_index"), "source": m.get("source")}
                        for d, dist, m in zip(docs, dists, metas)
                    ],
                    "metrics": {
                        "hit_at_1": contains_all(top1, q["key_terms"]),
                        "hit_at_5": any(contains_all(d, q["key_terms"]) for d in docs),
                        "top1_term_coverage": round(coverage(top1, q["key_terms"]), 2),
                        "top1_distance": round(float(dists[0]), 4) if dists else None,
                        "top1_clean_start": clean_start(top1),
                        "top1_clean_end": clean_end(top1),
                        "top1_length": len(top1),
                    },
                }
                m = reg["metrics"]
                print(f"  {regime:9s} hit@1={m['hit_at_1']!s:5} hit@5={m['hit_at_5']!s:5} "
                      f"cov={m['top1_term_coverage']:.2f} dist={m['top1_distance']:.3f} "
                      f"clean={m['top1_clean_start']}/{m['top1_clean_end']}")

                if not args.skip_llm:
                    context = "\n".join(
                        f"Document {i} (from {c['source']}):\n{c['text']}\n"
                        for i, c in enumerate(reg["chunks"], 1))
                    prompt = RAG_PROMPT.format(language=lang["name"], context=context,
                                               question=q["question"])
                    t0 = time.time()
                    answer = ollama_generate(args.ollama_url, args.answer_model, prompt)
                    reg["answer"] = answer
                    reg["answer_seconds"] = round(time.time() - t0, 1)
                    score, reason = judge(args.ollama_url, args.judge_model,
                                          q["question"], q["reference"], answer)
                    reg["judge_score"] = score
                    reg["judge_reason"] = reason
                    print(f"            answer {reg['answer_seconds']}s, judge score {score}: {reason[:90]}")
                entry["regimes"][regime] = reg
            out["queries"].append(entry)
        results["languages"][key] = out

    # Summary
    summary = {}
    for regime in REGIMES:
        rows = [q["regimes"][regime] for lang in results["languages"].values() for q in lang["queries"]]
        n = len(rows)
        s = {
            "queries": n,
            "hit_at_1": sum(r["metrics"]["hit_at_1"] for r in rows),
            "hit_at_5": sum(r["metrics"]["hit_at_5"] for r in rows),
            "mean_top1_term_coverage": round(sum(r["metrics"]["top1_term_coverage"] for r in rows) / n, 3),
            "mean_top1_distance": round(sum(r["metrics"]["top1_distance"] for r in rows) / n, 4),
            "clean_boundaries": sum(r["metrics"]["top1_clean_start"] and r["metrics"]["top1_clean_end"] for r in rows),
        }
        scores = [r["judge_score"] for r in rows if r.get("judge_score") is not None]
        if scores:
            s["mean_judge_score"] = round(sum(scores) / len(scores), 2)
            s["judged"] = len(scores)
        summary[regime] = s
    results["summary"] = summary

    Path(args.output).write_text(json.dumps(results, indent=2, ensure_ascii=False))
    print("\n=== SUMMARY ===")
    print(json.dumps(summary, indent=2))
    print(f"\nWrote {args.output}")


if __name__ == "__main__":
    sys.exit(main())
